        [Fact]
        public void ShouldValidateRealTaskArtifact_WhenTask1PreflightHasRun()
        {
            var repoRoot = FindRepoRoot();
            var dateSegment = DateTime.UtcNow.ToString("yyyy-MM-dd");
            var taskJsonPath = Path.Combine(repoRoot, "logs", "ci", dateSegment, TaskFileName);

            File.Exists(taskJsonPath).Should().BeTrue("task-0001.json must be generated by Task1 preflight");
            var taskJson = File.ReadAllText(taskJsonPath);

            var gate = EvaluateWindowsOnlyGate(taskJson, evidencePath =>
            {
                var absolutePath = Path.Combine(repoRoot, evidencePath.Replace("/", Path.DirectorySeparatorChar.ToString()));
                if (!File.Exists(absolutePath))
                {
                    return (false, string.Empty);
                }

                return (true, File.ReadAllText(absolutePath));
            });
            gate.IsPass.Should().BeTrue(gate.Reason);
            gate.StopDownstream.Should().BeFalse();

            using var document = JsonDocument.Parse(taskJson);
            document.RootElement.GetProperty(OsPlatformProperty).GetString().Should().Be(WindowsPlatform);

            var windowsCheck = document.RootElement.GetProperty(WindowsOnlyCheckProperty);
            var evidencePath = windowsCheck.GetProperty(EvidenceFileProperty).GetString();
            evidencePath.Should().NotBeNullOrWhiteSpace("windows_only_check.evidence_file is required");
            var evidenceAbsolutePath = Path.Combine(repoRoot, evidencePath!.Replace("/", Path.DirectorySeparatorChar.ToString()));
            File.Exists(evidenceAbsolutePath).Should().BeTrue("windows_only_check.evidence_file must point to existing artifact");

            var platformEvidence = windowsCheck.GetProperty(PlatformEvidenceProperty).GetString();
            platformEvidence.Should().NotBeNullOrWhiteSpace("platform_evidence is required");

            var evidenceText = File.ReadAllText(evidenceAbsolutePath);
            evidenceText.Should().Contain("result=pass", "windows-only evidence must include explicit pass result");
            evidenceText.Should().Contain(platformEvidence!, "windows-only evidence must include platform_evidence value");
        }

