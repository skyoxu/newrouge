        private static GateEvaluation EvaluateWindowsOnlyGate(
            string task0001Json,
            Func<string, (bool Exists, string Content)>? evidenceReader = null)
        {
            if (string.IsNullOrWhiteSpace(task0001Json))
            {
                return GateEvaluation.Fail(TaskFileName + " evidence is required.");
            }

            JsonDocument document;
            try
            {
                document = JsonDocument.Parse(task0001Json);
            }
            catch (JsonException)
            {
                return GateEvaluation.Fail(TaskFileName + " content is not valid JSON.");
            }

            using (document)
            {
                var osPlatform = document.RootElement.TryGetProperty(OsPlatformProperty, out var osPlatformElement)
                    ? osPlatformElement.GetString()
                    : null;
                if (!string.Equals(osPlatform, WindowsPlatform, StringComparison.OrdinalIgnoreCase))
                {
                    return GateEvaluation.Fail(OsPlatformProperty + " must be Windows.");
                }

                if (!document.RootElement.TryGetProperty(WindowsOnlyCheckProperty, out var checkElement) ||
                    checkElement.ValueKind != JsonValueKind.Object)
                {
                    return GateEvaluation.Fail(WindowsOnlyCheckProperty + " is required.");
                }

                var resultValue = checkElement.TryGetProperty(ResultProperty, out var resultElement)
                    ? resultElement.GetString()
                    : null;
                if (!string.Equals(resultValue, PassValue, StringComparison.OrdinalIgnoreCase))
                {
                    return GateEvaluation.Fail(WindowsOnlyCheckProperty + "." + ResultProperty + " must be pass.");
                }

                var evidence = checkElement.TryGetProperty(PlatformEvidenceProperty, out var evidenceElement)
                    ? evidenceElement.GetString()
                    : null;
                if (string.IsNullOrWhiteSpace(evidence))
                {
                    return GateEvaluation.Fail("platform evidence is required.");
                }

                var evidenceFile = checkElement.TryGetProperty(EvidenceFileProperty, out var evidenceFileElement)
                    ? evidenceFileElement.GetString()
                    : null;
                if (string.IsNullOrWhiteSpace(evidenceFile))
                {
                    return GateEvaluation.Fail("windows_only_check.evidence_file is required.");
                }

                if (evidenceReader is not null)
                {
                    var evidenceResult = evidenceReader(evidenceFile);
                    if (!evidenceResult.Exists)
                    {
                        return GateEvaluation.Fail("windows_only_check.evidence_file does not exist.");
                    }

                    if (!evidenceResult.Content.Contains(evidence, StringComparison.OrdinalIgnoreCase))
                    {
                        return GateEvaluation.Fail("windows_only_check.evidence_file must contain platform_evidence.");
                    }
                }
            }

            return GateEvaluation.Pass();
        }

        private static string FindRepoRoot()
        {
            var current = new DirectoryInfo(AppContext.BaseDirectory);
            while (current is not null)
            {
                if (File.Exists(Path.Combine(current.FullName, "NewRouge.sln")))
                {
                    return current.FullName;
                }

                current = current.Parent;
            }

            throw new InvalidOperationException("Unable to locate repository root containing NewRouge.sln.");
        }

        private sealed class GateEvaluation
        {
            private GateEvaluation(bool isPass, bool stopDownstream, string reason)
            {
                IsPass = isPass;
                StopDownstream = stopDownstream;
                Reason = reason;
            }

            public bool IsPass { get; }

            public bool StopDownstream { get; }

            public string Reason { get; }

            public static GateEvaluation Pass()
            {
                return new GateEvaluation(true, false, string.Empty);
            }

            public static GateEvaluation Fail(string reason)
            {
                return new GateEvaluation(false, true, reason);
            }
        }
