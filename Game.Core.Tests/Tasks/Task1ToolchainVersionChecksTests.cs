    [Fact]
    public async Task ShouldReportGodot451_WhenRunningVersionCommands()
    {
        var godotBinPath = Environment.GetEnvironmentVariable("GODOT_BIN");
        godotBinPath.Should().NotBeNullOrWhiteSpace("GODOT_BIN must be set to the pinned Godot executable path");
        ArgumentNullException.ThrowIfNull(godotBinPath);
        File.Exists(godotBinPath!).Should().BeTrue("GODOT_BIN should point to an existing executable file");

        var godotExeName = Path.GetFileName(godotBinPath);
        var godotExeDirectory = Path.GetDirectoryName(godotBinPath);

        Path.IsPathRooted(godotBinPath).Should().BeTrue("GODOT_BIN must be an absolute path on Windows");
        godotExeName.Should().NotBeNullOrWhiteSpace("GODOT_BIN must include executable file name");
        godotExeDirectory.Should().NotBeNullOrWhiteSpace("GODOT_BIN must include executable directory");
        ArgumentNullException.ThrowIfNull(godotExeName);
        ArgumentNullException.ThrowIfNull(godotExeDirectory);
        ContainsToken(godotExeName, "mono").Should().BeTrue("GODOT_BIN must target Godot .NET (mono) binary");
        ContainsToken(godotExeName, "console").Should().BeTrue("GODOT_BIN must target Godot console binary");

        var godotFromEnvBin = await RunProcessAsync(godotBinPath, "--version");
        var godotFromPath = await RunProcessAsync(
            "powershell",
            "-NoProfile -ExecutionPolicy Bypass -Command \"godot --version\"",
            prependPath: godotExeDirectory);

        godotFromEnvBin.ExitCode.Should().Be(0, godotFromEnvBin.DebugOutput);

        OutputContainsToken(godotFromEnvBin.StdOut, "4.5.1").Should().BeTrue(
            "& $env:GODOT_BIN --version stdout must include 4.5.1");
        OutputContainsToken(godotFromEnvBin.StdOut, "mono").Should().BeTrue(
            "& $env:GODOT_BIN --version stdout must prove mono flavor for .NET build");
        if (godotFromPath.ExitCode == 0)
        {
            OutputContainsToken(godotFromPath.StdOut, "4.5.1").Should().BeTrue(
                "when PATH is configured, godot --version stdout must include 4.5.1");
            OutputContainsToken(godotFromPath.StdOut, "mono").Should().BeTrue(
                "when PATH is configured, godot --version stdout must prove mono flavor for .NET build");
        }

        var repoRoot = FindRepoRoot();
        var dateSegment = DateTime.UtcNow.ToString("yyyy-MM-dd");
        var taskJsonPath = Path.Combine(repoRoot, "logs", "ci", dateSegment, "task-0001.json");

        File.Exists(taskJsonPath).Should().BeTrue("task-0001.json must be generated by acceptance preflight before Task1 tests run");
        ValidateGodotCommandEvidence(taskJsonPath, repoRoot, godotBinPath);
    }

