    private static bool OutputContainsToken(string output, string token)
    {
        return !string.IsNullOrWhiteSpace(output)
               && output.Contains(token, StringComparison.OrdinalIgnoreCase);
    }

    private static bool IsValidGodotCommandEvidence(int exitCode, string output)
    {
        return exitCode == 0 && OutputContainsToken(output, "4.5.1");
    }

    private static bool IsValidDotnetVersionCommand(int exitCode, string output)
    {
        if (exitCode != 0)
        {
            return false;
        }

        var firstLine = GetFirstNonEmptyLine(output);
        return !string.IsNullOrWhiteSpace(firstLine) && firstLine.StartsWith("8.", StringComparison.Ordinal);
    }

    private static bool HasDotnet8Sdk(int exitCode, string output)
    {
        if (exitCode != 0 || string.IsNullOrWhiteSpace(output))
        {
            return false;
        }

        var sdkVersions = output
            .Split(new[] { '\r', '\n' }, StringSplitOptions.RemoveEmptyEntries)
            .Select(line => line.Trim())
            .Where(line => line.Length > 0)
            .Select(line => line.Split(' ', StringSplitOptions.RemoveEmptyEntries)[0])
            .ToArray();

        return sdkVersions.Any(version => version.StartsWith("8.", StringComparison.Ordinal));
    }

    private static bool IsValidGodotBinContract(string? godotBinPath)
    {
        if (string.IsNullOrWhiteSpace(godotBinPath))
        {
            return false;
        }

        if (!Path.IsPathRooted(godotBinPath))
        {
            return false;
        }

        var exeName = Path.GetFileName(godotBinPath);
        return ContainsToken(exeName, "mono") && ContainsToken(exeName, "console");
    }

    private static bool IsValidGodotBinEnvScope(string? scope)
    {
        if (string.IsNullOrWhiteSpace(scope))
        {
            return false;
        }

        return string.Equals(scope, "Process", StringComparison.OrdinalIgnoreCase)
               || string.Equals(scope, "User", StringComparison.OrdinalIgnoreCase)
               || string.Equals(scope, "Machine", StringComparison.OrdinalIgnoreCase);
    }

    private static bool IsSemanticEquivalentRestoreToNewRouge(string? command)
    {
        if (string.IsNullOrWhiteSpace(command))
        {
            return false;
        }

        var tokens = command.Split(' ', StringSplitOptions.RemoveEmptyEntries)
            .Select(token => token.Replace("\"", string.Empty).Trim())
            .ToArray();
        if (tokens.Length < 3)
        {
            return false;
        }

        if (!tokens[0].EndsWith("dotnet", StringComparison.OrdinalIgnoreCase) &&
            !tokens[0].EndsWith("dotnet.exe", StringComparison.OrdinalIgnoreCase))
        {
            return false;
        }

        if (!string.Equals(tokens[1], "restore", StringComparison.OrdinalIgnoreCase))
        {
            return false;
        }

        var slnToken = tokens.Skip(2).FirstOrDefault(token => token.EndsWith(".sln", StringComparison.OrdinalIgnoreCase));
        if (string.IsNullOrWhiteSpace(slnToken))
        {
            return false;
        }

        var fileName = Path.GetFileName(slnToken.Replace("/", "\\"));
        return string.Equals(fileName, "NewRouge.sln", StringComparison.OrdinalIgnoreCase);
    }

    private static bool ContainsToken(string value, string token)
    {
        return value.Contains(token, StringComparison.OrdinalIgnoreCase);
    }

    private static string GetFirstNonEmptyLine(string output)
    {
        return output
            .Split(new[] { '\r', '\n' }, StringSplitOptions.RemoveEmptyEntries)
            .Select(line => line.Trim())
            .FirstOrDefault(line => line.Length > 0) ?? string.Empty;
    }

    private static string FindRepoRoot()
    {
        var current = new DirectoryInfo(AppContext.BaseDirectory);
        while (current is not null)
        {
            if (File.Exists(Path.Combine(current.FullName, "NewRouge.sln")))
            {
                return current.FullName;
            }

            current = current.Parent;
        }

        throw new InvalidOperationException("Unable to locate repository root containing NewRouge.sln.");
    }

    private static void ValidateGodotCommandEvidence(string taskJsonPath, string repoRoot, string expectedGodotBinPath)
    {
        using var document = JsonDocument.Parse(File.ReadAllText(taskJsonPath));
        var root = document.RootElement;

        root.TryGetProperty("godot_bin", out var godotBin).Should().BeTrue("task-0001.json must include godot_bin path");
        var godotBinPath = godotBin.GetString();
        godotBinPath.Should().NotBeNullOrWhiteSpace("task-0001.json must persist absolute GODOT_BIN path");
        Path.IsPathRooted(godotBinPath!).Should().BeTrue("task-0001.json must persist absolute GODOT_BIN path");
        godotBinPath.Should().Be(expectedGodotBinPath, "task-0001.json must preserve the current GODOT_BIN path");

        root.TryGetProperty("godot_bin_check", out var godotBinCheck).Should().BeTrue("task-0001.json must include godot_bin_check");
        godotBinCheck.TryGetProperty("installation_verification_result", out var installResult).Should().BeTrue("godot_bin_check.installation_verification_result is required");
        installResult.GetString().Should().Be("pass", "installation verification must pass for task 1");
        ValidateGodotBinEnv(root, repoRoot, expectedGodotBinPath);

        root.TryGetProperty("godot_commands", out var commands).Should().BeTrue("task-0001.json must include godot_commands");
        if (commands.TryGetProperty("godot_version_command", out _))
        {
            ValidateCommandEntry(commands, "godot_version_command", repoRoot);
        }
        ValidateCommandEntry(commands, "godot_bin_version_command", repoRoot);
    }

    private static void ValidateGodotBinEnv(JsonElement root, string repoRoot, string expectedGodotBinPath)
    {
        root.TryGetProperty("godot_bin_env", out var envInfo).Should().BeTrue("task-0001.json must include godot_bin_env");
        envInfo.TryGetProperty("env_var_name", out var envVarName).Should().BeTrue("godot_bin_env.env_var_name is required");
        envInfo.TryGetProperty("env_var_value", out var envVarValue).Should().BeTrue("godot_bin_env.env_var_value is required");
        envInfo.TryGetProperty("env_var_scope", out var envVarScope).Should().BeTrue("godot_bin_env.env_var_scope is required");
        envInfo.TryGetProperty("evidence_file", out var envEvidenceFile).Should().BeTrue("godot_bin_env.evidence_file is required");

        envVarName.GetString().Should().Be("GODOT_BIN");
        var envVarValueString = envVarValue.GetString();
        envVarValueString.Should().Be(expectedGodotBinPath);
        Path.IsPathRooted(envVarValueString!).Should().BeTrue("godot_bin_env.env_var_value must be absolute");
        IsValidGodotBinEnvScope(envVarScope.GetString()).Should().BeTrue("godot_bin_env.env_var_scope must be Process/User/Machine");

        var envEvidenceRelativePath = envEvidenceFile.GetString();
        envEvidenceRelativePath.Should().NotBeNullOrWhiteSpace("godot_bin_env.evidence_file must be populated");
        var envEvidenceAbsolutePath = Path.Combine(repoRoot, envEvidenceRelativePath!.Replace("/", Path.DirectorySeparatorChar.ToString()));
        File.Exists(envEvidenceAbsolutePath).Should().BeTrue("godot_bin_env.evidence_file must resolve to an existing file");
        var envEvidenceContent = File.ReadAllText(envEvidenceAbsolutePath);
        envEvidenceContent.Should().Contain("env_var_name=GODOT_BIN");
        envEvidenceContent.Should().Contain($"env_var_value={expectedGodotBinPath}");
    }

    private static void ValidateDotnetSdkEvidence(string taskJsonPath, string repoRoot)
    {
        using var document = JsonDocument.Parse(File.ReadAllText(taskJsonPath));
        var root = document.RootElement;

        root.TryGetProperty("dotnet_sdk_check", out var sdkCheck).Should().BeTrue("task-0001.json must include dotnet_sdk_check");
        sdkCheck.TryGetProperty("command", out var command).Should().BeTrue("dotnet_sdk_check.command is required");
        command.GetString().Should().Be("dotnet --list-sdks");

        sdkCheck.TryGetProperty("exit_code", out var exitCode).Should().BeTrue("dotnet_sdk_check.exit_code is required");
        exitCode.GetInt32().Should().Be(0, "dotnet --list-sdks must succeed");

        sdkCheck.TryGetProperty("has_dotnet8_sdk", out var hasDotnet8).Should().BeTrue("dotnet_sdk_check.has_dotnet8_sdk is required");
        hasDotnet8.GetBoolean().Should().BeTrue("dotnet --list-sdks must contain at least one 8.x SDK entry");

        sdkCheck.TryGetProperty("detected_sdk_versions", out var detectedVersions).Should().BeTrue("dotnet_sdk_check.detected_sdk_versions is required");
        detectedVersions.ValueKind.Should().Be(JsonValueKind.Array, "dotnet_sdk_check.detected_sdk_versions must be array");
        detectedVersions.EnumerateArray()
            .Select(item => item.GetString())
            .Where(item => !string.IsNullOrWhiteSpace(item))
            .Any(version => version!.StartsWith("8.", StringComparison.Ordinal))
            .Should()
            .BeTrue("detected_sdk_versions must include at least one 8.x entry");

        sdkCheck.TryGetProperty("evidence_file", out var evidenceFile).Should().BeTrue("dotnet_sdk_check.evidence_file is required");
        var evidenceRelativePath = evidenceFile.GetString();
        evidenceRelativePath.Should().NotBeNullOrWhiteSpace("dotnet_sdk_check.evidence_file must be populated");
        var evidenceAbsolutePath = Path.Combine(repoRoot, evidenceRelativePath!.Replace("/", Path.DirectorySeparatorChar.ToString()));
        File.Exists(evidenceAbsolutePath).Should().BeTrue("dotnet_sdk_check.evidence_file must resolve to existing file");
        var evidenceContent = File.ReadAllText(evidenceAbsolutePath);
        HasDotnet8Sdk(0, evidenceContent).Should().BeTrue("dotnet_sdk_check evidence file must include at least one 8.x SDK entry");
    }

