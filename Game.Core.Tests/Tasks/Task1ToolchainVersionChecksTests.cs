    private static void ValidateCommandEntry(JsonElement commands, string commandKey, string repoRoot)
    {
        commands.TryGetProperty(commandKey, out var entry).Should().BeTrue($"task-0001.json must include {commandKey}");
        entry.TryGetProperty("command", out _).Should().BeTrue($"{commandKey}.command is required");
        entry.TryGetProperty("exit_code", out var exitCode).Should().BeTrue($"{commandKey}.exit_code is required");
        entry.TryGetProperty("parsed_version", out var parsedVersion).Should().BeTrue($"{commandKey}.parsed_version is required");
        entry.TryGetProperty("evidence_file", out var evidenceFile).Should().BeTrue($"{commandKey}.evidence_file is required");

        var commandExitCode = exitCode.GetInt32();
        var parsedVersionValue = parsedVersion.GetString();
        IsValidGodotCommandEvidence(commandExitCode, parsedVersionValue ?? string.Empty).Should().BeTrue(
            $"{commandKey} must succeed and persist pinned 4.5.1 version");

        var commandValue = entry.TryGetProperty("command", out var commandElement) ? commandElement.GetString() : string.Empty;
        commandValue.Should().NotBeNullOrWhiteSpace($"{commandKey}.command must contain executable command text");
        if (string.Equals(commandKey, "godot_version_command", StringComparison.Ordinal))
        {
            commandValue.Should().Contain("godot --version");
        }
        else if (string.Equals(commandKey, "godot_bin_version_command", StringComparison.Ordinal))
        {
            commandValue.Should().Contain("$env:GODOT_BIN");
        }

        var evidenceRelativePath = evidenceFile.GetString();
        evidenceRelativePath.Should().NotBeNullOrWhiteSpace($"{commandKey}.evidence_file must be populated");
        var evidenceAbsolutePath = Path.Combine(repoRoot, evidenceRelativePath!.Replace("/", Path.DirectorySeparatorChar.ToString()));
        File.Exists(evidenceAbsolutePath).Should().BeTrue($"{commandKey}.evidence_file must resolve to an existing file");

        var evidenceContent = File.ReadAllText(evidenceAbsolutePath);
        IsValidGodotCommandEvidence(0, evidenceContent).Should().BeTrue(
            $"{commandKey}.evidence_file must include pinned Godot version output");
    }

    private static async Task<CommandResult> RunProcessAsync(string fileName, string arguments, string? prependPath = null)
    {
        try
        {
            var startInfo = new ProcessStartInfo
            {
                FileName = fileName,
                Arguments = arguments,
                UseShellExecute = false,
                RedirectStandardOutput = true,
                RedirectStandardError = true,
                CreateNoWindow = true
            };

            if (!string.IsNullOrWhiteSpace(prependPath))
            {
                var currentPath = Environment.GetEnvironmentVariable("PATH") ?? string.Empty;
                startInfo.Environment["PATH"] = prependPath + ";" + currentPath;
            }

            using var process = Process.Start(startInfo);
            if (process is null)
            {
                return CommandResult.StartFailure(fileName, arguments, "Process.Start returned null.");
            }

            var stdOutTask = process.StandardOutput.ReadToEndAsync();
            var stdErrTask = process.StandardError.ReadToEndAsync();

            using var timeoutCts = new CancellationTokenSource(CommandTimeout);
            try
            {
                await process.WaitForExitAsync(timeoutCts.Token);
            }
            catch (OperationCanceledException)
            {
                try
                {
                    if (!process.HasExited)
                    {
                        process.Kill(entireProcessTree: true);
                    }
                }
                catch
                {
                }

                var timeoutStdOut = await stdOutTask;
                var timeoutStdErr = await stdErrTask;
                return new CommandResult(
                    -1,
                    timeoutStdOut,
                    timeoutStdErr,
                    fileName,
                    arguments,
                    $"Command exceeded timeout of {CommandTimeout.TotalSeconds:0} seconds.");
            }

            var stdOut = await stdOutTask;
            var stdErr = await stdErrTask;
            return new CommandResult(process.ExitCode, stdOut, stdErr, fileName, arguments, string.Empty);
        }
        catch (Exception ex)
        {
            return CommandResult.StartFailure(fileName, arguments, ex.Message);
        }
    }

    private sealed record CommandResult(
        int ExitCode,
        string StdOut,
        string StdErr,
        string FileName,
        string Arguments,
        string StartError)
    {
        public string DebugOutput =>
            $"Command: {FileName} {Arguments}{Environment.NewLine}" +
            $"ExitCode: {ExitCode}{Environment.NewLine}" +
            $"StartError: {(string.IsNullOrEmpty(StartError) ? "<none>" : StartError)}{Environment.NewLine}" +
            $"StdOut: {StdOut}{Environment.NewLine}" +
            $"StdErr: {StdErr}";

        public static CommandResult StartFailure(string fileName, string arguments, string startError)
        {
            return new CommandResult(
                -1,
                string.Empty,
                string.Empty,
                fileName,
                arguments,
                startError);
        }
    }
