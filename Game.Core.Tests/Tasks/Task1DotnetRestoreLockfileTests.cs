    [Theory]
    [InlineData("dotnet restore .\\NewRouge.sln", true)]
    [InlineData("dotnet restore ./NewRouge.sln", true)]
    [InlineData("dotnet restore \"C:\\repo\\NewRouge.sln\" --verbosity minimal", true)]
