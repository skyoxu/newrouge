    [Fact]
    public async Task ShouldGeneratePackagesLockFile_WhenMissingBeforeDotnetRestore()
    {
        var repoRoot = FindRepoRoot();
        var lockfilePath = Path.Combine(repoRoot, "packages.lock.json");
        var backupPath = lockfilePath + ".task1.backup";
        var existedInitially = File.Exists(lockfilePath);

        await TestGate.WaitAsync();
        try
        {
            if (File.Exists(backupPath))
            {
                File.Delete(backupPath);
            }

            if (existedInitially)
            {
                File.Copy(lockfilePath, backupPath, overwrite: true);
                File.Delete(lockfilePath);
            }

            File.Exists(lockfilePath).Should().BeFalse("the test precondition requires a missing lock file");

            var restore = await RunDotnetRestoreAsync(repoRoot);

            restore.ExitCode.Should().Be(0, restore.CombinedOutput);
            File.Exists(lockfilePath).Should().BeTrue("dotnet restore must generate packages.lock.json when it is missing");
        }
        finally
        {
            if (existedInitially && File.Exists(backupPath))
            {
                File.Copy(backupPath, lockfilePath, overwrite: true);
                File.Delete(backupPath);
            }
            else if (!existedInitially && File.Exists(lockfilePath))
            {
                File.Delete(lockfilePath);
            }

            TestGate.Release();
        }
    }

