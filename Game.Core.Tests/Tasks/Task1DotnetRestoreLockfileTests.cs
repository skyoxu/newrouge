    private static string FindRepoRoot()
    {
        var current = new DirectoryInfo(AppContext.BaseDirectory);
        while (current is not null)
        {
            if (File.Exists(Path.Combine(current.FullName, "NewRouge.sln")))
            {
                return current.FullName;
            }

            current = current.Parent;
        }

        throw new InvalidOperationException("Unable to locate repository root containing NewRouge.sln.");
    }

    private static async Task<DotnetRestoreResult> RunDotnetRestoreAsync(string repoRoot)
    {
        var startInfo = new ProcessStartInfo
        {
            FileName = "dotnet",
            Arguments = "restore .\\NewRouge.sln",
            WorkingDirectory = repoRoot,
            UseShellExecute = false,
            RedirectStandardOutput = true,
            RedirectStandardError = true,
            StandardOutputEncoding = Encoding.UTF8,
            StandardErrorEncoding = Encoding.UTF8,
            CreateNoWindow = true,
        };

        using var process = Process.Start(startInfo);
        process.Should().NotBeNull("dotnet CLI must be available to execute restore");

        var stdOutTask = process!.StandardOutput.ReadToEndAsync();
        var stdErrTask = process.StandardError.ReadToEndAsync();

        var waitTask = process.WaitForExitAsync();
        var completed = await Task.WhenAny(waitTask, Task.Delay(RestoreTimeout));
        if (completed != waitTask)
        {
            var killError = string.Empty;
            try
            {
                if (!process.HasExited)
                {
                    process.Kill(entireProcessTree: true);
                }
            }
            catch (Exception ex)
            {
                killError = ex.Message;
            }

            await Task.WhenAny(process.WaitForExitAsync(), Task.Delay(TimeSpan.FromSeconds(5)));
            var timeoutStdOut = await ReadTaskWithTimeoutAsync(stdOutTask, TimeSpan.FromSeconds(2), "<stdout unavailable>");
            var timeoutStdErr = await ReadTaskWithTimeoutAsync(stdErrTask, TimeSpan.FromSeconds(2), "<stderr unavailable>");
            var timeoutMessage = $"dotnet restore timeout after {RestoreTimeout.TotalSeconds:0}s";
            if (!string.IsNullOrWhiteSpace(killError))
            {
                timeoutMessage += $"; kill error: {killError}";
            }

            return new DotnetRestoreResult(-1, timeoutStdOut, string.Concat(timeoutStdErr, Environment.NewLine, timeoutMessage));
        }

        var stdOut = await ReadTaskWithTimeoutAsync(stdOutTask, TimeSpan.FromSeconds(5), "<stdout read timeout>");
        var stdErr = await ReadTaskWithTimeoutAsync(stdErrTask, TimeSpan.FromSeconds(5), "<stderr read timeout>");
        return new DotnetRestoreResult(process.ExitCode, stdOut, stdErr);
    }

    private static async Task<string> ReadTaskWithTimeoutAsync(Task<string> readTask, TimeSpan timeout, string fallback)
    {
        var completed = await Task.WhenAny(readTask, Task.Delay(timeout));
        if (completed == readTask)
        {
            return await readTask;
        }

        return fallback;
    }

    private static void ValidateDotnetRestoreEvidence(string taskJsonPath, string repoRoot)
    {
        File.Exists(taskJsonPath).Should().BeTrue("task-0001.json must exist for dotnet_restore evidence mapping");
        var solutionPath = Path.Combine(repoRoot, "NewRouge.sln");
        File.Exists(solutionPath).Should().BeTrue("NewRouge.sln must exist in repository workspace for Task1 restore acceptance");

        using var document = JsonDocument.Parse(File.ReadAllText(taskJsonPath));
        var root = document.RootElement;

        root.TryGetProperty("dotnet_restore", out var dotnetRestore).Should().BeTrue("task-0001.json must include dotnet_restore section");
        dotnetRestore.TryGetProperty("command", out var command).Should().BeTrue("dotnet_restore.command is required");
        dotnetRestore.TryGetProperty("exit_code", out var exitCode).Should().BeTrue("dotnet_restore.exit_code is required");
        dotnetRestore.TryGetProperty("evidence_file", out var evidenceFile).Should().BeTrue("dotnet_restore.evidence_file is required");

        var commandValue = command.GetString();
        IsSemanticEquivalentRestoreToNewRouge(commandValue).Should().BeTrue(
            "dotnet_restore.command must semantically target NewRouge.sln using dotnet restore");
        exitCode.GetInt32().Should().Be(0, "dotnet restore must succeed for acceptance evidence");

        var evidenceRelativePath = evidenceFile.GetString();
        evidenceRelativePath.Should().NotBeNullOrWhiteSpace("dotnet_restore.evidence_file must be a relative artifact path");
        var evidenceAbsolutePath = Path.Combine(repoRoot, evidenceRelativePath!.Replace("/", Path.DirectorySeparatorChar.ToString()));
        File.Exists(evidenceAbsolutePath).Should().BeTrue("dotnet_restore.evidence_file must point to an existing artifact file");
        File.ReadAllText(evidenceAbsolutePath).Should().NotBeNullOrWhiteSpace("dotnet restore evidence content must not be empty");
    }

    private static bool IsSemanticEquivalentRestoreToNewRouge(string? command)
    {
        if (string.IsNullOrWhiteSpace(command))
        {
            return false;
        }

        var tokens = TokenizeCommand(command);
        if (tokens.Count < 3)
        {
            return false;
        }

        var executable = tokens[0].Replace("\"", string.Empty).Trim();
        var verb = tokens[1].Replace("\"", string.Empty).Trim();
        if (!executable.EndsWith("dotnet", StringComparison.OrdinalIgnoreCase) &&
            !executable.EndsWith("dotnet.exe", StringComparison.OrdinalIgnoreCase))
        {
            return false;
        }

        if (!string.Equals(verb, "restore", StringComparison.OrdinalIgnoreCase))
        {
            return false;
        }

        foreach (var token in tokens.Skip(2))
        {
            var cleaned = token.Replace("\"", string.Empty).Trim();
            if (!cleaned.EndsWith(".sln", StringComparison.OrdinalIgnoreCase))
            {
                continue;
            }

            var fileName = Path.GetFileName(cleaned.Replace("/", "\\"));
            return string.Equals(fileName, "NewRouge.sln", StringComparison.OrdinalIgnoreCase);
        }

        return false;
    }

    private static List<string> TokenizeCommand(string command)
    {
        var tokens = new List<string>();
        var current = new StringBuilder();
        var inQuotes = false;

        foreach (var ch in command)
        {
            if (ch == '"')
            {
                inQuotes = !inQuotes;
                current.Append(ch);
                continue;
            }

            if (char.IsWhiteSpace(ch) && !inQuotes)
            {
                if (current.Length > 0)
                {
                    tokens.Add(current.ToString());
                    current.Clear();
                }

                continue;
            }

            current.Append(ch);
        }

        if (current.Length > 0)
        {
            tokens.Add(current.ToString());
        }

        return tokens;
    }

    private static string BuildPersistedRestoreEvidence(DotnetRestoreResult restore)
    {
        if (string.IsNullOrEmpty(restore.StdErr))
        {
            return restore.StdOut;
        }

        return restore.StdOut + "\n" + restore.StdErr;
    }

    private static string NormalizeLineEndings(string value)
    {
        return value.Replace("\r\n", "\n", StringComparison.Ordinal);
    }

    private sealed record DotnetRestoreResult(int ExitCode, string StdOut, string StdErr)
    {
        public string CombinedOutput => string.Concat(StdOut, Environment.NewLine, StdErr);
    }
